interface Props {
  text: string;
  /** Dot pitch in px. */
  dot: number;
  color?: string;
  /** Colour of unlit dots ("" hides them). */
  dim?: string;
  className?: string;
  /** Fixed number of character cells (right-aligned), e.g. 3 for speed. */
  cells?: number;
}

export const DotText = memo(function DotText({ text, dot, color = "currentColor", dim = "", className, cells }: Props) {
  const chars = (cells ? text.padStart(cells, " ") : text).toUpperCase().split("");
  const cw = 6; // 5 dots + 1 gap
  const w = chars.length * cw - 1, h = 7;
  const r = 0.42;
  return (
    <svg className={className} width={w * dot} height={h * dot} viewBox={`0 0 ${w} ${h}`} aria-label={text}>
      {chars.map((ch, ci) => {
        const rows = (F[ch] ?? F[" "]).split(" ");
        return rows.map((row, y) => row.split("").map((b, x) => {
          if (b !== "1" && !dim) return null;
          return <circle key={`${ci}-${x}-${y}`} cx={ci * cw + x + 0.5} cy={y + 0.5} r={r} fill={b === "1" ? color : dim} />;
        }));
      })}
    </svg>
  );
});
